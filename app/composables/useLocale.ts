export type MessageKey = keyof typeof zh

export function useLocale() {
  const ledger = useState<LedgerSnapshot>('ledger')
  const locale = computed<Language>(() => ledger.value?.settings?.language ?? 'zh-CN')
  const t = (key: MessageKey, values: Record<string, string | number> = {}) => {
    let message: string = (locale.value === 'en' ? en : zh)[key]
    for (const [name, value] of Object.entries(values)) message = message.replaceAll(`{${name}}`, String(value))
    return message
  }
  return { locale, t }
}
